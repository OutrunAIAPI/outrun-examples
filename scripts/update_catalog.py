#!/usr/bin/env python3
"""Regenerate CATALOG.md from Outrun's public price feed.

Usage:
    python scripts/update_catalog.py          # rewrite CATALOG.md
    python scripts/update_catalog.py --check  # exit 1 if CATALOG.md is out of date

Sources (both public, no API key needed):
    https://api.outrun.to/pricing     active models (paused models are skipped)
    https://outrun.to/sitemap.xml     which models have a /model/<slug> page

Prices are deliberately left out of CATALOG.md so it never goes stale.
Live prices: https://outrun.to/model/
"""

import json
import re
import sys
import urllib.request
from collections import OrderedDict
from pathlib import Path

FEED_URL = "https://api.outrun.to/pricing"
SITEMAP_URL = "https://outrun.to/sitemap.xml"
SITE = "https://outrun.to"
UTM = "utm_source=github&utm_medium=repo&utm_campaign=examples"
OUT = Path(__file__).resolve().parent.parent / "CATALOG.md"

KIND_TITLES = OrderedDict(
    [
        ("text", "Text and coding models"),
        ("image", "Image models"),
        ("video", "Video models"),
        ("audio", "Speech models"),
    ]
)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "outrun-examples/update_catalog"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8")


def link(path, anchor=""):
    """outrun.to link with the repo's UTM tag (query goes before the #anchor)."""
    return f"{SITE}{path}?{UTM}" + (f"#{anchor}" if anchor else "")


def page_for(model_id, active_ids, slugs):
    """Return (slug, anchor) of the /model/ page for an ID, or (None, None)."""
    slug = model_id.lower()
    if slug in slugs:
        return slug, ""
    m = re.match(r"^(.*)-(\d+)$", slug)
    if m and m.group(1) in slugs:
        base = m.group(1)
        # "x-2" is route 2 of model "x" when "x" itself is a live model ID;
        # otherwise the page simply drops the route suffix.
        if any(i.lower() == base for i in active_ids):
            return base, f"route-{m.group(2)}"
        return base, ""
    return None, None


def build():
    feed = json.loads(fetch(FEED_URL))
    paused = set(feed.get("paused") or [])
    models = [m for m in feed["models"] if m["id"] not in paused]
    for m in models:
        m.setdefault("name", m["id"])
        # "Uncensored · 3" style labels mark routes; list them under one family.
        m["family_label"] = re.sub(r"\s*·\s*\d+$", "", m.get("family_label") or "")
    active_ids = {m["id"] for m in models}

    sitemap = fetch(SITEMAP_URL)
    slugs = {
        s.rstrip("/")
        for s in re.findall(r"<loc>https://outrun\.to/model/([^<]+)</loc>", sitemap)
        if s.strip("/")
    }

    # Group route IDs (x-2, x-3) under the model page they belong to.
    pages = OrderedDict()
    unlinked = []
    for m in models:
        slug, anchor = page_for(m["id"], active_ids, slugs)
        if slug is None:
            unlinked.append(m)
            continue
        entry = pages.setdefault(slug, {"model": None, "routes": [], "kind": m["kind"]})
        if anchor:
            entry["routes"].append(m)
        elif entry["model"] is None:
            entry["model"] = m
        else:
            entry["routes"].append(m)

    for entry in pages.values():
        if entry["model"] is None:  # page reached only through route IDs
            entry["model"] = entry["routes"].pop(0)

    lines = [
        "# Outrun model catalog",
        "",
        "> Every active model on Outrun, with the exact model ID to send to "
        "`https://api.outrun.to/v1` and a link to its page (price, context, setup values).",
        "> Generated by `scripts/update_catalog.py` from the public feed "
        "https://api.outrun.to/pricing. Paused models are left out.",
        "",
        f"- Models: {len(pages)} (plus {sum(len(e['routes']) for e in pages.values())} "
        "alternative route IDs)",
        f"- Live prices: [{SITE}/model/]({link('/model/')})",
        f"- Machine-readable summary: [{SITE}/llms.txt]({link('/llms.txt')})",
        "",
        "Route IDs are the same model through another route at a different price; "
        "the model page compares them.",
        "",
    ]

    for kind, title in KIND_TITLES.items():
        group = [(s, e) for s, e in pages.items() if e["kind"] == kind]
        # Keep each family together, in the order the feed first lists it.
        order = {}
        for _, e in group:
            order.setdefault(e["model"].get("family_label") or "", len(order))
        group.sort(key=lambda se: order[se[1]["model"].get("family_label") or ""])
        if not group:
            continue
        lines += [f"## {title}", ""]
        family = None
        for slug, e in group:
            fam = e["model"].get("family_label") or ""
            if kind == "text" and fam != family:
                family = fam
                lines += ["", f"### {fam}", ""]
            m = e["model"]
            lines.append(f"- [{m['name']}]({link('/model/' + slug)}): `{m['id']}`")
            for r in e["routes"]:
                _, anchor = page_for(r["id"], active_ids, slugs)
                lines.append(f"  - ↳ route: `{r['id']}` ([compare]({link('/model/' + slug, anchor)}))")
        lines.append("")

    if unlinked:
        lines += ["## Other active IDs", ""]
        for m in unlinked:
            lines.append(f"- {m['name']}: `{m['id']}`")
        lines.append("")

    # Collapse blank-line runs from the family headers.
    text = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip() + "\n"
    return text, len(pages)


def main():
    text, count = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("CATALOG.md is out of date; run scripts/update_catalog.py")
            return 1
        print(f"CATALOG.md is current ({count} models)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {count} models")
    return 0


if __name__ == "__main__":
    sys.exit(main())
